#!/usr/bin/env python3
"""Generate host ESSL for the 3D vehicle model materials (bmw/widgetasset/vehicles/<model>/vehicle).

The BMW car materials share one structure (see their native interfaces): the vertex stage
computes a lit base shade (v_BaseShade from LightADir/diffColor), a reflection vector (v_Refl,
optionally with a fresnel term in .w), uv + vertex colour (varCoordUVColRG) and a highlight
colour (v_highlight = HighlightColor * Highlight); the fragment stage adds an environment
reflection (EnvTex) and optional diffuse/AO textures. This generator rebuilds that structure
per material family (paint, chrome/rim, plastic, glass, lights, ground, interior, masks) from the
interface alone. Paint colour can be forced (PAINT_RGB) so the model matches the owner's car.

Usage (WSL): make-car-model-shaders.py ROOTFS_RO MODEL_DIR [--write]
  e.g. ... /root/.cache/.../data/ro bmw/widgetasset/vehicles/F30/vehicle --write
"""
import hashlib
import importlib.util
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MAPS = ROOT / "tools/shaders/native-reconstructions"
TYPES = {2: "float", 3: "vec2", 4: "vec3", 5: "vec4", 0x16: "mat4", 0x18: "sampler2D"}
# Owner's car: F30 340i, grey (Mineral Grey metallic B39 approximated in linear-ish sRGB).
PAINT_RGB = (0.27, 0.29, 0.31)

spec = importlib.util.spec_from_file_location("insp", Path(__file__).with_name("inspect-sgx-shader.py"))
insp = importlib.util.module_from_spec(spec)
spec.loader.exec_module(insp)


def symbols(path):
    out = {"uniform": {}, "attr": {}, "out": {}, "in": {}}
    for s in insp.parse_shader(path)["symbols"]:
        m = bytes.fromhex(s["metadata_hex"])
        cls = {3: "uniform", 4: "attr", 5: "out", 6: "in"}.get(m[3])
        if cls and s["name"] != "gl_Position":
            out[cls][s["name"]] = TYPES.get(m[2])
    return out


def family(name):
    n = name.upper()
    for key, fam in (("CARPAINT", "paint"), ("PDCCARPAINT", "pdc"), ("CHROME", "chrome"), ("WHEELRIM", "chrome"),
                     ("GLASS", "glass"), ("LIGHT", "light"), ("FOG", "light"), ("GROUND", "ground"),
                     ("INTERIOR", "interior"), ("MASK", "mask"), ("CUT", "mask"), ("QUAD_RL", "quad"),
                     ("LOGO", "chrome"), ("BRAKEDISC", "metal"), ("WHEELCOAT", "plastic")):
        if key in n:
            return "pdc" if "PDCCARPAINT" in n else fam
    return "plastic"


def default(t, what="one"):
    if t == "float":
        return "1.0" if what == "one" else "0.0"
    return f"{t}({'1.0' if what == 'one' else '0.0'})"


def vertex(name, sy):
    a, u, o = sy["attr"], sy["uniform"], sy["out"]
    fam = family(name)
    if None in list(a.values()) + list(u.values()) + list(o.values()) or ("a_Position" not in a and fam != "quad"):
        return None
    L = ["#version 300 es", f"// Generated by tools/make-car-model-shaders.py ({fam}) for {name}.", "precision highp float;"]
    L += [f"uniform {t} {n};" for n, t in u.items()]
    L += [f"in {t} {n};" for n, t in a.items()]
    L += [f"out {t} {n};" for n, t in o.items()]
    B = []
    if fam == "quad" and "u_rectangle" in u:
        B.append("    vec2 tc = a_TextureCoordinate;")
        B.append("    gl_Position = vec4(u_rectangle.xy + tc * u_rectangle.zw, 0.0, 1.0);")
    else:
        B.append("    vec4 p = vec4(a_Position.xyz, 1.0);")
        B.append("    gl_Position = u_MVPMatrix * p;" if "u_MVPMatrix" in u else "    gl_Position = p;")
    model = "u_MMatrix" in u
    pos = "a_Position.xyz" if "a_Position" in a else "vec3(0.0)"
    B.append("    vec3 h_wp = " + (f"(u_MMatrix * vec4({pos}, 1.0)).xyz;" if model else f"{pos};"))
    B.append("    vec3 h_n = " + ("normalize(mat3(u_MMatrix) * a_Normal);" if "a_Normal" in a and model
                              else "normalize(a_Normal);" if "a_Normal" in a else "vec3(0.0, 1.0, 0.0);"))
    B.append("    vec3 h_eye = " + ("normalize(h_wp - u_CameraWorldPosition);" if "u_CameraWorldPosition" in u else "vec3(0.0, 0.0, -1.0);"))
    B.append("    vec3 h_ldir = " + ("normalize(-LightADir);" if "LightADir" in u else "normalize(vec3(0.3, 1.0, 0.4));"))
    B.append("    float h_diff = clamp(dot(h_n, h_ldir), 0.0, 1.0) * 0.65 + 0.35;")
    if fam == "paint":
        base = "vec3(%.3f, %.3f, %.3f)" % PAINT_RGB
    elif "diffColor" in u:
        base = "diffColor"
    else:
        base = {"chrome": "vec3(0.55)", "glass": "vec3(0.05, 0.06, 0.07)", "metal": "vec3(0.35)",
                "light": "vec3(0.8)", "interior": "vec3(0.25)"}.get(fam, "vec3(0.06)")
    hl = "HighlightColor * Highlight" if "HighlightColor" in u and "Highlight" in u else "vec3(0.0)"
    for n_, t in o.items():
        if n_ == "v_BaseShade":
            B.append(f"    v_BaseShade = {base} * h_diff;")
        elif n_ == "v_Refl":
            r = "reflect(h_eye, h_n)"
            B.append(f"    v_Refl = {r};" if t == "vec3" else
                     f"    v_Refl = vec4({r}, pow(1.0 - clamp(dot(-h_eye, h_n), 0.0, 1.0), 3.0));")
        elif n_ == "varCoordUVColRG":
            col = "a_Color.rg" if "a_Color" in a else "vec2(1.0)"
            tc = "a_TextureCoordinate.xy" if "a_TextureCoordinate" in a else "vec2(0.0)"
            B.append(f"    varCoordUVColRG = vec4({tc}, {col});")
        elif n_ == "v_highlight":
            B.append(f"    v_highlight = {hl};")
        elif n_ in ("varCoord", "uv", "UV", "varCoords", "uvCoord", "varCoord2", "varCoords2", "varCoordsGround", "varCoordsStreet"):
            if fam == "quad":
                # u_rectangleSrc arrives as NaN/inf from the HMI: the layer texture is sampled whole.
                B.append(f"    {n_} = a_TextureCoordinate;")
            elif t == "vec2":
                B.append(f"    {n_} = " + ("a_TextureCoordinate.xy;" if "a_TextureCoordinate" in a else "vec2(0.0);"))
            else:
                B.append(f"    {n_} = {default(t, 'zero')};")
        elif n_ in ("normal",):
            B.append("    normal = h_n;")
        elif n_ in ("worldpos", "worldpos2"):
            B.append(f"    {n_} = h_wp;")
        elif n_ == "v_worldpos":
            B.append("    v_worldpos = vec4(h_wp, 1.0);")
        elif n_ == "eye":
            B.append("    eye = h_eye;")
        elif n_ in ("tangent", "binormal"):
            src = "a_Tangent" if n_ == "tangent" else "a_Binormal"
            B.append(f"    {n_} = " + (f"normalize(mat3(u_MMatrix) * {src});" if src in a and model else f"{default(t, 'zero')};"))
        elif n_ == "col":
            src = "a_Color" if "a_Color" in a else "vec4(1.0)"
            B.append(f"    col = {src}" + ("" if t == "vec4" else ".rgb") + ";")
        elif n_ == "glasscol":
            B.append("    glasscol = " + ("diffColor;" if "diffColor" in u else "vec3(0.05, 0.06, 0.07);"))
        elif n_ == "lightup":
            ups = [x for x in ("lamp1", "lamp2", "indicator", "angelEyes", "LightOnEco", "u_EcoLight") if x in u]
            B.append("    lightup = " + (f"clamp(max({', '.join(ups)}, 0.0), 0.0, 1.0);" if len(ups) == 1 else
                                         "clamp(max(max(" + ", ".join(ups[:2]) + "), 0.0), 0.0, 1.0);" if ups else "0.0;"))
        elif n_ == "vAlpha":
            B.append("    vAlpha = 0.0;")
        else:
            B.append(f"    {n_} = {default(t, 'one')};")
    # keep every native attribute live (the HMI binds them by name)
    live = [f"{n} == -12345.5" if t == "float" else f"{n}.x == -12345.5" for n, t in a.items() if n != "a_Position" and t]
    if live:
        B.append(f"    if ({' && '.join(live)}) gl_Position.w += 1.0e-7;")
    return "\n".join(L + ["", "void main()", "{"] + B + ["}", ""])


def fragment(name, sy):
    i, u = sy["in"], sy["uniform"]
    if None in list(i.values()) + list(u.values()):
        return None
    fam = family(name)
    L = ["#version 300 es", f"// Generated by tools/make-car-model-shaders.py ({fam}) for {name}.", "precision highp float;"]
    L += [f"uniform {t} {n};" for n, t in u.items()]
    L += [f"in {t} {n};" for n, t in i.items()]
    L += ["layout(location = 0) out highp vec4 bmwFragmentColor;", "", "void main()", "{"]
    B = []
    if fam == "mask" or "GROUNDDSC" in name:
        B.append("    discard;")
        return "\n".join(L + B + ["}", ""])
    uvsrc = next((n for n in ("varCoordUVColRG", "varCoord", "uv", "UV", "uvCoord", "varCoords") if n in i), None)
    uv = f"{uvsrc}.xy" if uvsrc else "vec2(0.5)"
    if fam == "quad":
        B.append(f"    vec4 c = texture(tex0, {uv});")
        if "opacity" in u:
            B.append("    c.a *= clamp(opacity, 0.0, 1.0);")
        B.append("    bmwFragmentColor = c;")
        return "\n".join(L + B + ["}", ""])
    B.append("    vec3 c = " + ("v_BaseShade;" if "v_BaseShade" in i else "vec3(0.0);"))
    tex = next((n for n in ("DiffuseTex", "tex0", "tex", "Sampler", "tex1") if n in u), None)
    if "v_Refl" in i and "EnvTex" in u:
        B.append("    vec3 r = normalize(v_Refl.xyz);")
        B.append("    vec2 env = r.xy / (2.0 * sqrt(r.x * r.x + r.y * r.y + (r.z + 1.0) * (r.z + 1.0) + 1e-5)) + 0.5;")
        k = {"chrome": "0.85", "paint": "0.35", "glass": "0.45", "metal": "0.5"}.get(fam, "0.15")
        fres = " * (0.4 + 0.6 * v_Refl.w)" if i["v_Refl"] == "vec4" else ""
        B.append(f"    c += texture(EnvTex, env).rgb * {k}{fres};")
    alpha = "1.0"
    if tex and fam in ("light", "ground", "interior"):
        B.append(f"    vec4 t = texture({tex}, {uv});")
        # Light/ground textures are grey-level masks with a constant alpha (tex_lightadd,
        # tex_doorlight, tex_lightcones); the vehicle shadow packs separate masks in R/G/B and the
        # soft shadow in A.
        B.append("    float lum = max(t.r, max(t.g, t.b));")
        ons = [x for x in ("LightOn", "LightOnEco") if x in u]
        on = "1.0" if not ons else ons[0] if len(ons) == 1 else f"max({ons[0]}, {ons[1]})"
        if "lightup" in i:
            on = f"max({on}, lightup)" if on != "1.0" else "lightup"
        if fam == "light":
            B.append("    c = vec3(lum)" + (" * col.rgb" if "col" in i else "") + ";")
            alpha = f"lum * t.a * clamp({on}, 0.0, 1.0)"
        elif fam == "interior":
            B.append("    c = t.rgb" + (" * col.rgb" if "col" in i and i["col"] == "vec4" else "") + ";")
            alpha = "t.a"
        elif "GROUNDFRONT" in name or "GROUNDREAR" in name:
            B.append("    c = vec3(1.0, 0.95, 0.85) * lum;")
            alpha = f"lum * clamp({on}, 0.0, 1.0)"
        elif "GROUNDCARPET" in name:
            B.append("    c = vec3(lum);")
            alpha = "lum" + (" * clamp(intensity, 0.0, 1.0)" if "intensity" in u else "")
        else:                                            # vehicle shadow
            B.append("    c = vec3(0.0);")
            alpha = "t.a * 0.85"
    elif tex and fam in ("paint", "plastic", "metal", "chrome"):
        B.append(f"    c *= mix(vec3(1.0), texture({tex}, {uv}).rgb, 0.6);")
    if "v_highlight" in i:
        B.append("    c += v_highlight;")
    if fam == "glass":
        alpha = "0.55"
    if "u_Opacity" in u:
        alpha = f"({alpha}) * clamp(u_Opacity, 0.0, 1.0)"
    if "opacity" in u:
        alpha = f"({alpha}) * clamp(opacity, 0.0, 1.0)"
    if fam == "pdc":
        alpha = "0.0"
    B.append(f"    bmwFragmentColor = vec4(clamp(c, 0.0, 1.0), clamp({alpha}, 0.0, 1.0));")
    return "\n".join(L + B + ["}", ""])


def main():
    ro, model = Path(sys.argv[1]), sys.argv[2].strip("/")
    write = "--write" in sys.argv
    tag = model.replace("/", "_")
    out_dir = {"vertex": MAPS / f"hmi-vertex-car006/{tag}", "fragment": MAPS / f"hmi-fragment-car006/{tag}"}
    maps = {"vertex": MAPS / "hmi-vertex-map-car006.json", "fragment": MAPS / "hmi-fragment-map-car006.json"}
    data = {k: json.loads(p.read_text()) for k, p in maps.items()}
    mapped = {e["asset_path"] for d in data.values() for e in d["mappings"]}
    made = 0
    for shd in sorted((ro / model / "shaders").glob("*.shd")):
        asset = f"{model}/shaders/{shd.name}"
        stage = "vertex" if shd.name.endswith(".vert.shd") else "fragment"
        name = shd.name.replace(".shd", "")
        src = (vertex if stage == "vertex" else fragment)(name, symbols(shd))
        if src is None:
            print("skip", name)
            continue
        out = out_dir[stage] / f"{name}.glsl"
        rel = out.relative_to(ROOT).as_posix()
        made += 1
        if write:
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(src, encoding="utf-8", newline="\n")
            entry = next((e for e in data[stage]["mappings"] if e["asset_path"] == asset), None)
            if entry is None:
                entry = {"asset_path": asset}
                data[stage]["mappings"].append(entry)
            entry.update({"source_path": rel, "source_essl_sha256": hashlib.sha256(src.encode()).hexdigest(),
                          "basis": "generated by tools/make-car-model-shaders.py from the native interface"})
        print("gen", name, "->", rel)
    if write:
        for k, p in maps.items():
            p.write_text(json.dumps(data[k], indent=2) + "\n", encoding="utf-8", newline="\n")
    print("generated", made)


if __name__ == "__main__":
    main()
