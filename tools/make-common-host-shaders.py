#!/usr/bin/env python3
"""Generate host ESSL for the simple common/shader/*.shd families and add them to the car maps.

The BMW 2D shader library (Image*, Icon*, Rectangle*, Text*, ...) follows a strict naming scheme:
  vertex  : MVP transform; texture coordinates optionally mapped through a uTextureRectangle
            (xy = offset, zw = scale, see the exact Image_vertex reconstruction); *_fade*
            variants also output scroll-area fade factors (vFading).
  fragment: <format>_fragment[_repeat][_fade]; colour = u_color * sample, where the sample is
            RGBA, luminance or luminance+alpha; _repeat wraps the coordinates, _fade multiplies
            alpha by the fade factors.
Interfaces (names/types/inputs) are taken from the native symbols, so ANGLE links them with the
HMI's own uniform/attribute lookups. Families with geometry logic that is not obvious from the
interface (NinePart, TwentyFivePart, Roadbook, Teletext, SharedTexture with external samplers)
are skipped and stay unmapped.

Scroll-area fading is not reproduced yet (vFading = 1); the fade inputs are kept live with a
sentinel comparison so the HMI's attribute/uniform lookups still succeed.

Usage (WSL): make-common-host-shaders.py ROOTFS_RO [--write]
"""
import hashlib
import importlib.util
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MAPS = ROOT / "tools/shaders/native-reconstructions"
OUT_V = MAPS / "hmi-vertex-car006/common"
OUT_F = MAPS / "hmi-fragment-car006/common"
TYPES = {2: "float", 3: "vec2", 4: "vec3", 5: "vec4", 0x16: "mat4", 0x18: "sampler2D"}

spec = importlib.util.spec_from_file_location("insp", Path(__file__).with_name("inspect-sgx-shader.py"))
insp = importlib.util.module_from_spec(spec)
spec.loader.exec_module(insp)


def symbols(path):
    out = {"uniform": {}, "attr": {}, "out": {}, "in": {}}
    for s in insp.parse_shader(path)["symbols"]:
        m = bytes.fromhex(s["metadata_hex"])
        cls = {3: "uniform", 4: "attr", 5: "out", 6: "in"}.get(m[3])
        if cls and s["name"] != "gl_Position":
            out[cls][s["name"]] = TYPES.get(m[2])
    return out


def ones(t):
    return {"float": "1.0", "vec2": "vec2(1.0)", "vec3": "vec3(1.0)", "vec4": "vec4(1.0)"}[t]


def vertex(name, sy):
    a, u, o = sy["attr"], sy["uniform"], sy["out"]
    if any(t is None for t in list(a.values()) + list(u.values()) + list(o.values())):
        return None
    known = {"vTexCoord", "vTexCoord0", "vTexCoord1", "vTexCoord2", "vTexCoordA", "vTexCoordB",
             "vTexCoordSpecial", "vColor", "vFading", "fFading"}
    if set(o) - known or "a_Position" not in a or "u_MVPMatrix" not in u:
        return None
    lines = ["#version 300 es", f"// Generated by tools/make-common-host-shaders.py for common/shader/{name}.",
             "precision highp float;"]
    lines += [f"uniform {t} {n};" for n, t in u.items()]
    lines += [f"in {t} {n};" for n, t in a.items()]
    lines += [f"out {t} {n};" for n, t in o.items()]
    tc = "a_TextureCoordinate.xy" if "a_TextureCoordinate" in a else "vec2(0.0)"
    body = [f"    gl_Position = u_MVPMatrix * vec4(a_Position.xyz, 1.0);"]

    def rect(r):
        return f"{tc} * {r}.zw + {r}.xy" if r in u else tc
    for n in o:
        if n == "vTexCoord":
            body.append(f"    vTexCoord = {rect('uTextureRectangle')};")
        elif n == "vTexCoord0":
            body.append(f"    vTexCoord0 = {rect('uTextureRectangle')};")
        elif n == "vTexCoord1":
            body.append(f"    vTexCoord1 = {rect('uTextureRectangle1')};")
        elif n in ("vTexCoord2", "vTexCoordSpecial"):
            body.append(f"    {n} = {tc};")
        elif n == "vTexCoordA":
            body.append(f"    vTexCoordA = {rect('u_RectangleFrameA')};")
        elif n == "vTexCoordB":
            body.append(f"    vTexCoordB = {rect('u_RectangleFrameB')};")
        elif n == "vColor":
            body.append("    vColor = " + ("u_color;" if "u_color" in u else "a_Color;" if "a_Color" in a else "vec4(1.0);"))
    live = [f"{n} == -12345.5" for n, t in a.items() if t == "float"]
    live += [f"{n}.y == -12345.5" for n, t in u.items() if n == "u_scrollAreaFadeParameters"]
    live += [f"{n}[0][0] == -12345.5" for n, t in u.items() if n == "u_MC1Matrix"]
    for n in ("vFading", "fFading"):
        if n in o:
            keep = f"({' && '.join(live)} ? 0.999 : 1.0)" if live else "1.0"
            body.append(f"    {n} = {o[n]}({keep});" if o[n] != "float" else f"    {n} = {keep};")
    return "\n".join(lines + ["", "void main()", "{"] + body + ["}", ""])


def fragment(name, sy):
    i, u = sy["in"], sy["uniform"]
    if any(t is None for t in list(i.values()) + list(u.values())):
        return None
    base = name.split("_fragment")[0]
    repeat, fade = "_repeat" in name, name.endswith("_fade")
    tc = "vTexCoord" if "vTexCoord" in i else "vTexCoord0" if "vTexCoord0" in i else None
    if base in ("ImageRGBA", "IconRGBA", "ImageLuminanceAlpha"):
        sample = "texture(tex0, uv)"
    elif base == "ImageLuminance":
        sample = "vec4(texture(tex0, uv).rgb, 1.0)"
    elif base == "ContentShader":
        sample = "texture(tex0, uv)"
    elif base in ("Rectangle",) and fade:
        sample = None
    elif base.startswith("Gal3DDraw2D"):
        sample = ("vec4(1.0)" if "notex" in name else "vec4(texture(tex0, uv).rgb, 1.0)" if "luminance" in name
                  else "texture(tex0, uv)" if "tex_rgb" in name else None)
        if name == "Gal3DDraw2D_fragment":
            return None
    elif base == "SpecialText":
        sample = "texture(tex0, uv)"
    elif base == "ImageAnimation":
        sample = "texture(tex0, vTexCoordA)"
    elif base == "ImageAnimationBlend":
        sample = "mix(texture(tex0, vTexCoordA), texture(tex1, vTexCoordB), clamp(u_FrameBlending, 0.0, 1.0))"
    else:
        return None
    lines = ["#version 300 es", f"// Generated by tools/make-common-host-shaders.py for common/shader/{name}.",
             "precision highp float;"]
    lines += [f"uniform {t} {n};" for n, t in u.items()]
    lines += [f"in {t} {n};" for n, t in i.items()]
    lines += ["layout(location = 0) out highp vec4 bmwFragmentColor;", "", "void main()", "{"]
    if tc:
        if repeat and "uTextureWrapModeRepeat" in u:
            lines.append(f"    vec2 uv = mix({tc}, fract({tc}), step(vec2(0.5), uTextureWrapModeRepeat));")
        elif repeat and "u_userRepeatTexture" in u:
            lines.append(f"    vec2 uv = fract({tc} * max(u_userRepeatTexture, vec2(1.0)));")
        else:
            lines.append(f"    vec2 uv = {tc};")
    tint = "clamp(u_color, 0.0, 1.0)" if "u_color" in u else "vColor" if "vColor" in i else "vec4(1.0)"
    if base == "Rectangle":
        lines.append(f"    vec4 c = {tint};")
    else:
        lines.append(f"    vec4 c = {tint} * {sample};")
    if "u_ConstAlpha" in u:
        lines.append("    c.a *= clamp(u_ConstAlpha, 0.0, 1.0);")
    if "u_opacity" in u:
        lines.append("    c.a *= clamp(u_opacity, 0.0, 1.0);")
    if "fFading" in i:
        lines.append("    c.a *= clamp(fFading, 0.0, 1.0);")
    if fade and "vFading" in i:
        f = i["vFading"]
        lines.append("    c.a *= " + {"float": "vFading", "vec2": "vFading.x * vFading.y",
                                      "vec3": "vFading.x * vFading.y * vFading.z"}[f] + ";")
    lines += ["    bmwFragmentColor = clamp(c, 0.0, 1.0);", "}", ""]
    return "\n".join(lines)


def main():
    ro = Path(sys.argv[1])
    write = "--write" in sys.argv
    maps = {"vertex": MAPS / "hmi-vertex-library.json", "fragment": MAPS / "hmi-fragment-library.json"}  # then: shader-library.py sync
    data = {k: json.loads(p.read_text()) for k, p in maps.items()}
    mapped = {e["asset_path"] for d in data.values() for e in d["mappings"]}
    made = skipped = 0
    for shd in sorted((ro / "common/shader").glob("*.shd")):
        asset = f"common/shader/{shd.name}"
        if asset in mapped:
            continue
        name = shd.stem
        stage = "vertex" if "_vertex" in name else "fragment"
        src = (vertex if stage == "vertex" else fragment)(name, symbols(shd))
        if src is None:
            skipped += 1
            print(f"skip {name}")
            continue
        made += 1
        out = (OUT_V if stage == "vertex" else OUT_F) / f"{name}.glsl"
        rel = out.relative_to(ROOT).as_posix()
        print(f"gen  {name} -> {rel}")
        if write:
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(src, encoding="utf-8", newline="\n")
            data[stage]["mappings"].append({
                "asset_path": asset, "source_path": rel,
                "source_essl_sha256": hashlib.sha256(src.encode()).hexdigest(),
                "basis": "generated by tools/make-common-host-shaders.py from the native interface"})
    if write:
        for k, p in maps.items():
            p.write_text(json.dumps(data[k], indent=2) + "\n", encoding="utf-8", newline="\n")
    print(f"generated {made}, skipped {skipped}")


if __name__ == "__main__":
    main()
