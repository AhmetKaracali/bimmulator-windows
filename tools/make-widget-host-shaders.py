#!/usr/bin/env python3
"""Generate conservative host ESSL for unmapped widget materials (scene.pbx based).

For every widget directory (…/widgetasset/<name>/) the scene.pbx lists materials with their
textures and shader pair (mat_X -> shaders/mat_X.vert / .frag). Unmapped pairs get:
  vertex  : MVP transform, uv-like outputs from the texture coordinates, size_x/size_z stretch
            of template meshes (same formula as the verified CursorBG mat_bg.vert), fade window
            outputs (fd) fully open, scalar outputs 1.0, colour outputs from matching uniforms.
  fragment: only when the first sampled texture is a *picture* (RGB channels correlated, alpha
            carries the shape): colour = texture * tint, alpha = texture.a * opacity/intensity.
            Channel-packed mask textures are skipped (guessing the channel mix produced the
            green/blue artefacts before) - those stay unmapped and draw nothing.
Usage (Windows python, rootfs via \\wsl.localhost): make-widget-host-shaders.py RO [--write]
"""
import hashlib
import importlib.util
import json
import re
import sys
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
MAPS = ROOT / "tools/shaders/native-reconstructions"
TYPES = {2: "float", 3: "vec2", 4: "vec3", 5: "vec4", 0x16: "mat4", 0x18: "sampler2D"}
spec = importlib.util.spec_from_file_location("insp", Path(__file__).with_name("inspect-sgx-shader.py"))
insp = importlib.util.module_from_spec(spec)
spec.loader.exec_module(insp)


def symbols(path):
    out = {"uniform": {}, "attr": {}, "out": {}, "in": {}}
    for s in insp.parse_shader(path)["symbols"]:
        m = bytes.fromhex(s["metadata_hex"])
        cls = {3: "uniform", 4: "attr", 5: "out", 6: "in"}.get(m[3])
        if cls and s["name"] != "gl_Position":
            out[cls][s["name"]] = TYPES.get(m[2])
    return out


def materials(widget):
    """mat name -> {"vert": path, "frag": path, "textures": [bitmap png paths]}"""
    data = (widget / "scene.pbx").read_bytes()
    toks = [t.decode("latin-1").strip('"') for t in re.findall(rb"[\x20-\x7e]{3,}", data)]
    mats = {}
    for i, t in enumerate(toks):
        if t.startswith("shaders/") and t.endswith(".vert") and i + 1 < len(toks) and toks[i + 1].endswith(".frag"):
            mats.setdefault(toks[i - 1], {})["vert"] = t
            mats[toks[i - 1]]["frag"] = toks[i + 1]
    bitmaps = {p.name.split("tex", 1)[-1] if False else p.name: p for p in (widget / "bitmaps").glob("*.png")} \
        if (widget / "bitmaps").is_dir() else {}
    for i, t in enumerate(toks):
        base = t.split('"')[0]
        if base in mats and "textures" not in mats[base]:
            texs = []
            for u in toks[i + 1:i + 12]:
                if u.endswith("_bitmap"):
                    hit = next((p for n, p in bitmaps.items() if n.endswith(u + ".png")), None)
                    if hit:
                        texs.append(hit)
                elif u.startswith(("mat_", "shaders/")):
                    break
            if texs:
                mats[base]["textures"] = texs
    return mats


def is_picture(png):
    try:
        a = np.asarray(Image.open(png).convert("RGBA")).astype(np.float32) / 255.0
    except OSError:
        return False
    alpha = a[..., 3]
    if alpha.max() - alpha.min() < 0.2:          # constant alpha: channel masks / plain fills
        return False
    vis = alpha > 0.1
    if vis.sum() < 16:
        return False
    rgb = a[..., :3][vis]
    spread = np.abs(rgb[:, 0] - rgb[:, 1]).mean() + np.abs(rgb[:, 1] - rgb[:, 2]).mean()
    return spread < 0.25 or rgb.std(axis=0).mean() > 0.05


RESERVED = {"active", "input", "output", "filter", "sample", "common", "partition", "resource", "half",
            "fixed", "superp", "texture", "sampler", "attribute", "varying", "buffer", "shared", "patch"}


def unsupported(sy):
    names = [n for d in sy.values() for n in d]
    return any(n in RESERVED for n in names)


def aliases(sy):
    """gl_-prefixed native uniforms are renamed bmw_<name>; the ANGLE server maps them back."""
    lines = []
    for n in list(sy["uniform"]):
        if n.startswith("gl_"):
            host = "bmw_" + n[3:]
            sy["uniform"][host] = sy["uniform"].pop(n)
            lines.append(f"// IDRIVE_UNIFORM_ALIAS native={n} host={host}")
    return lines


def vertex(sy):
    if unsupported(sy):
        return None
    alias = aliases(sy)
    a, u, o = sy["attr"], sy["uniform"], sy["out"]
    if None in list(a.values()) + list(u.values()) + list(o.values()) or "a_Position" not in a or "u_MVPMatrix" not in u:
        return None
    L = ["#version 300 es", "// Generated by tools/make-widget-host-shaders.py.", *alias, "precision highp float;"]
    L += [f"uniform {t} {n};" for n, t in u.items()] + [f"in {t} {n};" for n, t in a.items()] + [f"out {t} {n};" for n, t in o.items()]
    tc = "a_TextureCoordinate.xy" if "a_TextureCoordinate" in a else "vec2(0.0)"
    B = ["    vec3 p = a_Position.xyz;"]
    if "size_x" in u and "a_TextureCoordinate" in a:
        B.append(f"    p.x += {tc}.x * size_x;")
    if "size_z" in u and "a_TextureCoordinate" in a:
        B.append(f"    p.z += {tc}.y * size_z;")
    B.append("    gl_Position = u_MVPMatrix * vec4(p, 1.0);")
    for n, t in o.items():
        if t == "vec2":
            src = "a_TextureCoordinate1.xy" if n.endswith("1") and "a_TextureCoordinate1" in a else tc
            B.append(f"    {n} = {src};")
        elif n in ("fd", "p_fd"):
            B.append(f"    {n} = vec3(0.0, 0.0, 1.0);")
        elif t == "vec3":
            col = next((x for x in u if x.startswith("CO") and u[x] == "vec3"), None)
            B.append(f"    {n} = {col if col else 'vec3(1.0)'};")
        elif t == "vec4":
            B.append(f"    {n} = " + ("vec4(a_TextureCoordinate.xy, a_TextureCoordinate1.xy);" if "a_TextureCoordinate1" in a and n.lower().startswith("var")
                                       else f"vec4({tc}, 0.0, 1.0);" if n.lower().startswith(("var", "uv")) else "vec4(1.0);"))
        else:
            B.append(f"    {n} = 1.0;")
    live = [f"{n} == -12345.5" if t == "float" else f"{n}.x == -12345.5" for n, t in a.items() if n != "a_Position"]
    if live:
        B.append(f"    if ({' && '.join(live)}) gl_Position.w += 1.0e-7;")
    return "\n".join(L + ["", "void main()", "{"] + B + ["}", ""])


def fragment(sy):
    if unsupported(sy):
        return None
    alias = aliases(sy)
    i, u = sy["in"], sy["uniform"]
    if None in list(i.values()) + list(u.values()):
        return None
    samplers = [n for n, t in u.items() if t == "sampler2D"]
    uvs = [n for n, t in i.items() if t == "vec2"] or [n for n, t in i.items() if t == "vec4"]
    if not samplers or not uvs:
        return None
    uv = uvs[0] + (".xy" if i[uvs[0]] == "vec4" else "")
    L = ["#version 300 es", "// Generated by tools/make-widget-host-shaders.py (picture texture).", *alias, "precision highp float;"]
    L += [f"uniform {t} {n};" for n, t in u.items()] + [f"in {t} {n};" for n, t in i.items()]
    L += ["layout(location = 0) out highp vec4 bmwFragmentColor;", "", "void main()", "{",
          f"    vec4 c = texture({samplers[0]}, {uv});"]
    for k in ("opacity", "Opacity", "u_opacity", "intensity"):
        if k in u and u[k] == "float":
            L.append(f"    c.a *= clamp({k}, 0.0, 1.0);")
    L += ["    bmwFragmentColor = clamp(c, 0.0, 1.0);", "}", ""]
    return "\n".join(L)


def main():
    ro = Path(sys.argv[1])
    write = "--write" in sys.argv
    maps = {"vertex": MAPS / "hmi-vertex-map-car006.json", "fragment": MAPS / "hmi-fragment-map-car006.json"}
    data = {k: json.loads(p.read_text()) for k, p in maps.items()}
    mapped_hash = set()
    for d in data.values():
        for e in d["mappings"]:
            p = ro / e["asset_path"]
            if p.exists():
                mapped_hash.add(hashlib.sha256(p.read_bytes()).hexdigest())
    done_hash = set(mapped_hash)
    made = {"vertex": 0, "fragment": 0}
    skipped = 0
    for scene in sorted(ro.glob("**/widgetasset/**/scene.pbx")):
        widget = scene.parent
        rel_widget = widget.relative_to(ro).as_posix()
        for mat, info in materials(widget).items():
            if "vert" not in info:
                continue
            pics = info.get("textures", [])
            frag_ok = bool(pics) and is_picture(pics[0])
            for stage, key in (("vertex", "vert"), ("fragment", "frag")):
                shd = widget / (info[key] + ".shd")
                if not shd.exists():
                    continue
                h = hashlib.sha256(shd.read_bytes()).hexdigest()
                if h in done_hash:
                    continue
                if stage == "fragment" and not frag_ok:
                    skipped += 1
                    continue
                src = (vertex if stage == "vertex" else fragment)(symbols(shd))
                if src is None:
                    skipped += 1
                    continue
                done_hash.add(h)
                made[stage] += 1
                tag = rel_widget.replace("/", "_")
                out = MAPS / f"hmi-{stage}-car006/widgets/{tag}/{Path(info[key]).name}.glsl"
                if write:
                    out.parent.mkdir(parents=True, exist_ok=True)
                    out.write_text(src, encoding="utf-8", newline="\n")
                    data[stage]["mappings"].append({
                        "asset_path": f"{rel_widget}/{info[key]}.shd",
                        "source_path": out.relative_to(ROOT).as_posix(),
                        "source_essl_sha256": hashlib.sha256(src.encode()).hexdigest(),
                        "basis": "generated by tools/make-widget-host-shaders.py (conservative)"})
    if write:
        for k, p in maps.items():
            p.write_text(json.dumps(data[k], indent=2) + "\n", encoding="utf-8", newline="\n")
    print("generated", made, "skipped", skipped)


if __name__ == "__main__":
    main()
